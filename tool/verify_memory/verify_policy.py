#!/usr/bin/env python3
"""Verify Rust test vectors by executing hash-pinned VMA FindMemoryPreferences."""
import argparse
import hashlib
import os
from pathlib import Path
import subprocess
import tempfile

import fetch_donor

ROOT = Path(__file__).resolve().parents[2]


def stage_headers(source, destination):
    """Admit only pinned inputs and reject accidental umbrella/system SDK use."""
    verified = {}
    for line in (ROOT / 'registry/ABI_SHA256SUMS').read_text().splitlines():
        expected, name = line.split()
        data = (source / name).read_bytes()
        if hashlib.sha256(data).hexdigest() != expected:
            raise ValueError('pinned header mismatch: ' + name)
        verified[name] = data
    for name, data in verified.items():
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    # Fail even on developer machines where the full SDK is installed. The
    # executable must build from the core/video headers in ABI_SHA256SUMS alone.
    umbrella = destination / 'vulkan/vulkan.h'
    umbrella.parent.mkdir(parents=True, exist_ok=True)
    umbrella.write_text('#error "Policy oracle must use the pinned Vulkan core declarations"\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--headers', required=True, type=Path)
    parser.add_argument('--refresh', action='store_true', help='replace the generated donor vectors')
    args = parser.parse_args()
    donor = ROOT / 'target/verify_memory/donor' / fetch_donor.COMMIT
    subprocess.run(['python3', str(Path(__file__).with_name('fetch_donor.py')), '--check'], check=True)
    output = ROOT / 'target/verification/memory-policy'
    output.mkdir(parents=True, exist_ok=True)
    binary = output / 'vma-policy'
    with tempfile.TemporaryDirectory(prefix='pinned-headers-', dir=output) as directory:
        headers = Path(directory)
        stage_headers(args.headers, headers)
        subprocess.run([os.environ.get('CXX', 'clang++'), '-std=c++17', '-O2',
                        '-isystem', str(donor / 'include'), '-isystem', str(headers),
                        str(Path(__file__).with_name('policy_oracle.cpp')), '-o', str(binary)], check=True)
    result = subprocess.run([str(binary)], check=True, capture_output=True)
    if result.stderr:
        raise ValueError('VMA oracle emitted diagnostics')
    data = (f'# @generated by tool/verify_memory/verify_policy.py; VMA {fetch_donor.COMMIT}\n'
            '# usage host transfer device integrated required preferred result_required result_preferred result_avoided\n').encode() + result.stdout
    fixture = ROOT / 'test/rs/memory/fixtures/policy.gen.tsv'
    if args.refresh:
        fixture.write_bytes(data)
    elif fixture.read_bytes() != data:
        raise ValueError('stale donor preference vectors; review and run --refresh')
    (output / 'policy.gen.tsv').write_bytes(data)
    print(f'Verified {len(result.stdout.splitlines())} pinned VMA memory preference cases')


if __name__ == '__main__':
    main()
