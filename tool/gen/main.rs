use anyhow::{Context, Result, bail, ensure};
use std::{
	io::Write,
	path::{Path, PathBuf},
	process::{Command, Stdio},
};
fn main() {
	if let Err(e) = run() {
		eprintln!("vk-gen: {e:#}");
		std::process::exit(1);
	}
}

fn run() -> Result<()> {
	let opts = parse_args(std::env::args().skip(1))?;
	if opts.help {
		println!(
			"vk-gen --registry <vk.xml> --video-registry <video.xml> --output <dir> [--check]\n--check compares formatted output without writing; audit and freshness failures exit nonzero."
		);
		return Ok(());
	}
	let registry = opts.registry.context("--registry is required")?;
	let video = opts
		.video_registry
		.context("--video-registry is required")?;
	let output = opts
		.output
		.context("--output is required, including in --check mode")?;
	let mut reg = parse::parse_registry(&registry, false)?;
	let v = parse::parse_registry(&video, true)?;
	for ty in v.types {
		if let Some(i) = reg.types.iter().position(|t| t.c_name == ty.c_name) {
			reg.types[i] = ty;
		} else {
			reg.types.push(ty);
		}
	}
	for e in v.enums {
		if let Some(existing) = reg.enums.iter_mut().find(|t| t.c_name == e.c_name) {
			ensure!(
				existing.backing == e.backing,
				"conflicting enum {}",
				e.c_name
			);
			existing.values.extend(e.values);
		} else {
			reg.enums.push(e);
		}
	}
	for (name, clauses) in v.provisions {
		for clause in clauses {
			protect::provide(&mut reg.provisions, &name, clause);
		}
	}
	reg.protections.extend(v.protections);
	for (name, requirements) in v.command_requirements {
		reg
			.command_requirements
			.entry(name)
			.or_default()
			.extend(requirements);
	}
	reg.constants.extend(v.constants);
	reg.features.extend(v.features);
	reg.extensions.extend(v.extensions);
	resolve::resolve(&mut reg)?;
	let errors = audit::audit(&reg);
	ensure!(
		errors.is_empty(),
		"registry audit failed:\n{}",
		errors.join("\n")
	);
	let types = emit_types::emit_types(&reg)?;
	let (commands, command_tests) = emit_commands::emit_commands(&reg)?;
	let files = [
      ("src/rs/core/type.gen.rs", types),
      ("src/rs/load/feature.gen.rs", emit_features::emit_features(&reg)?),
      ("src/rs/core/enum.gen.rs", emit_enums::emit_enums(&reg)?),
      ("src/rs/core/constant.gen.rs", emit_constants::emit_constants(&reg)?),
      ("src/rs/core/pfn.gen.rs", emit_pfn::emit_pfn(&reg)),
      ("src/rs/core/dispatch.gen.rs", emit_dispatch::emit_dispatch(&reg)),
      ("src/rs/core/command.gen.rs", commands),
      ("test/rs/core/test_command.gen.rs", command_tests),
      ("src/rs/core/export.gen.rs", "// @generated by vk-gen — core ABI exports.\npub use super::{types::*, enums::*, constants::*, pfn::*, dispatch::*, extensions::*};\n".into()),
      ("src/rs/core/extension.gen.rs", emit_metadata::emit_metadata(&reg)?),
      ("tool/gen/abi.gen.tsv", emit_abi_names(&reg)),
    ];
	let files = files
		.into_iter()
		.map(|(name, text)| {
			Ok((
				name,
				if name.ends_with(".rs") {
					format_generated(&text)?
				} else {
					text
				},
			))
		})
		.collect::<Result<Vec<_>>>()?;
	if !opts.check {
		std::fs::create_dir_all(&output)?;
	}
	let mut stale = vec![];
	for (name, text) in files {
		let path = output.join(name);
		if opts.check {
			match std::fs::read(&path) {
				Ok(actual) if actual == text.as_bytes() => {}
				Ok(_) => stale.push(format!("stale: {}", path.display())),
				Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
					stale.push(format!("missing: {}", path.display()))
				}
				Err(e) => return Err(e).with_context(|| format!("reading {}", path.display())),
			}
		} else {
			std::fs::create_dir_all(path.parent().unwrap())?;
			if std::fs::read(&path).ok().as_deref() != Some(text.as_bytes()) {
				std::fs::write(&path, text).with_context(|| format!("writing {}", path.display()))?;
			}
		}
	}
	ensure!(
		stale.is_empty(),
		"generated output differs:\n{}",
		stale.join("\n")
	);
	eprintln!(
		"{}: {} types, {} enums, {} commands, {} extensions",
		if opts.check { "Verified" } else { "Generated" },
		reg.types.len(),
		reg.enums.len(),
		reg.commands.len(),
		reg.extensions.len()
	);
	Ok(())
}

/// The ABI oracle uses the same names as the emitters; C names stay available
/// for offsetof while Rust fields and bitfield accessors use native spelling.
fn emit_abi_names(reg: &model::Registry) -> String {
	let mut out = String::from("# @generated by vk-gen: C type, Rust type, C field, Rust field\n");
	for ty in &reg.types {
		let members = match &ty.kind {
			model::TypeKind::Struct { members, .. } | model::TypeKind::Union { members } => members,
			_ => continue,
		};
		for member in members {
			out.push_str(&format!(
				"{}\t{}\t{}\t{}\n",
				ty.c_name,
				names::type_name(&ty.c_name),
				member.name,
				names::member_name(&member.name)
			));
		}
	}
	out
}

/// Whitespace only: stable rustfmt preserves these item separators.
fn space_items(source: &str) -> String {
	let mut out = String::new();
	let mut previous = "";
	for line in source.lines() {
		let next = line.trim_start();
		if previous.trim_end().ends_with('}')
			&& !out.ends_with("\n\n")
			&& (next.starts_with("///")
				|| next.starts_with("#[")
				|| next.starts_with("impl ")
				|| next.starts_with("unsafe impl ")
				|| next.starts_with("pub ")
				|| next.starts_with("fn "))
		{
			out.push('\n');
		}
		out.push_str(line);
		out.push('\n');
		previous = line;
	}
	out
}

fn format_generated(text: &str) -> Result<String> {
	let config = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../rustfmt.toml");
	let mut child = Command::new("rustfmt")
		.args(["--edition", "2024", "--config-path"])
		.arg(config)
		.stdin(Stdio::piped())
		.stdout(Stdio::piped())
		.stderr(Stdio::piped())
		.spawn()
		.context("rustfmt is required for deterministic generation")?;
	// A writer thread prevents a pipe deadlock on large generated files.
	let mut stdin = child.stdin.take().unwrap();
	let input = text.as_bytes().to_owned();
	let writer = std::thread::spawn(move || stdin.write_all(&input));
	let output = child.wait_with_output()?;
	writer
		.join()
		.map_err(|_| anyhow::anyhow!("rustfmt writer panicked"))??;
	ensure!(
		output.status.success(),
		"rustfmt rejected generated code: {}",
		String::from_utf8_lossy(&output.stderr)
	);
	Ok(space_items(&String::from_utf8(output.stdout)?))
}

#[derive(Default, Debug)]
struct Opts {
	help: bool,
	check: bool,
	registry: Option<PathBuf>,
	video_registry: Option<PathBuf>,
	output: Option<PathBuf>,
}

fn parse_args(args: impl Iterator<Item = String>) -> Result<Opts> {
	let mut opts = Opts::default();
	let mut args = args.peekable();
	while let Some(arg) = args.next() {
		match arg.as_str() {
			"--help" | "-h" => opts.help = true,
			"--check" => opts.check = true,
			"--registry" | "--video-registry" | "--output" => {
				let value = args
					.next()
					.filter(|s| !s.starts_with('-'))
					.with_context(|| format!("{arg} requires a path"))?;
				let slot = match arg.as_str() {
					"--registry" => &mut opts.registry,
					"--video-registry" => &mut opts.video_registry,
					_ => &mut opts.output,
				};
				ensure!(slot.is_none(), "duplicate option {arg}");
				*slot = Some(value.into());
			}
			_ => bail!("unknown argument {arg}"),
		}
	}
	Ok(opts)
}

